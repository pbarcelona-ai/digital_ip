#!/usr/bin/env python3
# ***************
# Filename: sv_ifconv.py
# Author: FPGA Cores 4 U
# Description: Converts annotated discrete port groups into SystemVerilog
#   interface ports, and every parent / testbench that connects them.
#   An annotated group in a module header:
#       // s_axis: axis_if.slave (ip/shared/src/interfaces/axis_if.sv), DATA_W = 24
#       input  logic [23:0] s_axis_tdata,  ...          (ports <group>_<member>)
#   or with an explicit port -> member map:
#       // vid: vid_if.sink (ip/shared/src/interfaces/vid_if.sv), DATA_W = 24 {rgb_i=data de_i=de}
#   Register interfaces <ip>_regs_if (generated by regmap_gen.py) use the
#   member names as port names (cfg_* / sts_*).
#   Pass 1 reads every module of ip/ and image_processing/ (module table:
#   annotated groups, also already converted ones). Pass 2 rewrites the files
#   given on the command line, modules last to first:
#     - instances of a module with groups: the group's connections become one
#       interface connection. When the parent connects P_<member> nets (or
#       P.<member>) of its own interface port / instance P, P is passed; simple
#       local nets are absorbed into a new interface instance (declarations
#       removed, references renamed to P.<member>, also inside `included test
#       files); anything else gets an adapter instance <inst>_<group> with
#       continuous assigns;
#     - the module's own groups become interface ports, body references
#       <port> -> <group>.<member>, and the members the module never drove are
#       tied off (unless the whole interface is handed to a child).
#   Tool rules this follows (tested with Icarus 14, Verilator 5, Yosys + sv2v
#   / slang): widths as module parameters (no $bits of interface members),
#   connections by plain instance name, top-level synthesis via syn_wrap.py.
#   Usage: python3 ip/scripts/sv_ifconv.py [--dry] FILE...
# Date: 2026-10-16

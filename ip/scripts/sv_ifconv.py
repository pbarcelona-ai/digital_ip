# member: (direction seen from the master / source modport, tie-off when a module lacks it)
IFACES = {
    "axis_if": {"first": "master", "members": {
        "tdata": ("o", "'0"), "tkeep": ("o", "'1"), "tlast": ("o", "1'b0"), "tuser": ("o", "'0"),
        "tvalid": ("o", None), "tready": ("i", "1'b1")},
        "width": {"DATA_W": "tdata", "USER_W": "tuser", "KEEP_W": "tkeep"}},
    "axil_if": {"first": "master", "members": {
        "awaddr": ("o", None), "awvalid": ("o", None), "awready": ("i", None), "wdata": ("o", None),
        "wstrb": ("o", "'1"), "wvalid": ("o", None), "wready": ("i", None), "bresp": ("i", None),
        "bvalid": ("i", None), "bready": ("o", None), "araddr": ("o", None), "arvalid": ("o", None),
        "arready": ("i", None), "rdata": ("i", None), "rresp": ("i", None), "rvalid": ("i", None),
        "rready": ("o", None)},
        "width": {"ADDR_W": "awaddr", "DATA_W": "wdata"}},
}
MONITOR = {"monitor"}


def load_iface_file(path):
    """Add an interface from its source: member directions from its first modport; tie-offs 0 ('1 for
    strobes); width hints '// width <PARAM> = <member>'."""
    s = open(path, encoding="utf-8").read()
    m = re.search(r"^\s*interface\s+(\w+)", s, re.M)
    if not m or m.group(1) in IFACES:
        return
    mps = re.findall(r"modport\s+(\w+)\s*\(([^;]*)\)\s*;", s)
    if not mps:
        return
    first, body = mps[0]
    members, d = {}, None
    for tok in re.split(r"[\s,]+", body):
        if tok in ("input", "output", "inout"):
            d = "o" if tok == "output" else "i"
        elif re.match(r"^\w+$", tok) and d:
            members[tok] = (d, "'1" if tok.endswith("strb") else "'0")
    widths = dict(re.findall(r"//\s*width\s+(\w+)\s*=\s*(\w+)", s))
    IFACES[m.group(1)] = {"first": first, "members": members, "width": widths}


def drives_o(iface, mp):
    return mp == IFACES[iface]["first"]


# ------------------------------------------------------------------ text helpers
def mask(text):
    """Same-length copy with comments and strings blanked."""
    out = list(text)
    i, n = 0, len(text)
    while i < n:
        if text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out[i:j] = " " * (j - i)
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            for k in range(i, j):
                if out[k] != "\n":
                    out[k] = " "
            i = j
        elif text[i] == '"':
            j = i + 1
            while j < n and text[j] != '"':
                j += 2 if text[j] == "\\" else 1
            for k in range(i + 1, min(j, n)):
                out[k] = " "
            i = j + 1
        else:
            i += 1
    return "".join(out)


def match_paren(m, i):
    depth = 0
    for j in range(i, len(m)):
        if m[j] == "(":
            depth += 1
        elif m[j] == ")":
            depth -= 1
            if depth == 0:
                return j
    raise ValueError("unbalanced parentheses")


def split_items(m, a, b):
    items, depth, s = [], 0, a
    for j in range(a, b):
        c = m[j]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
        elif c == "," and depth == 0:
            items.append((s, j))
            s = j + 1
    items.append((s, b))
    return [(x, y) for x, y in items if m[x:y].strip()]


def width_of(rng):
    """'[23:0]' -> '24', '[PW-1:0]' -> 'PW', '[3*PW-1:0]' -> '3*PW', '' -> '1'."""
    if not rng:
        return "1"
    r = rng.strip()[1:-1]
    hi, lo = [x.strip() for x in r.split(":", 1)]
    if lo != "0":
        return f"({hi}) - ({lo}) + 1"
    mm = re.match(r"^(.*?)\s*-\s*1$", hi)
    if mm:
        e = mm.group(1).strip()
        return e if re.match(r"^[\w.*/()]+$", e) else f"({e})"
    if re.match(r"^\d+$", hi):
        return str(int(hi) + 1)
    return f"({hi}) + 1"


# ------------------------------------------------------------------ module table
ANN = re.compile(r"^(\s*)//\s*(\w+):\s*(\w+)\.(\w+)\s*\(([^)]*)\)(.*)$")
PORT = re.compile(r"^\s*(input|output|inout)\s+(?:(?:wire|logic|var|reg)\s+)?(?:signed\s+)?"
                  r"((?:\[[^\]]*\]\s*)*)(\w+)\s*(,?)\s*(//.*)?$")
SV_KEYWORDS = set("""always and assign automatic begin bit buf byte case cell config const default defparam do
edge else end endcase endfunction endmodule event for force forever fork function generate genvar if
initial inout input int integer interface join logic module nand negedge nor not or output parameter
posedge real reg repeat return shortint signed specify string struct supply0 supply1 table task time tri
type typedef union unsigned var void wait while wire xor""".split())
CONST = re.compile(r"^(\d*'[sS]?[bdhoBDHO][0-9a-fA-FxXzZ_]+|'[01xXzZ]|\d+|'0|'1)$")
IFPORT = re.compile(r"^\s*(\w+)\.(\w+)\s+(\w+)\s*,?\s*(//.*)?$")


class Group:
    def __init__(self, name, iface, mp, params, pmap):
        self.name, self.iface, self.mp, self.params, self.pmap = name, iface, mp, params, pmap
        self.ports = {}                            # discrete port -> (dir, range)

    def same_names(self):
        return self.iface.endswith("_regs_if")

    def member_of(self, port):
        mem = IFACES[self.iface]["members"]
        if self.pmap:
            return self.pmap.get(port)
        if self.same_names():
            return port if port in mem else None
        if port.startswith(self.name + "_") and port[len(self.name) + 1:] in mem:
            return port[len(self.name) + 1:]
        return None

    def discrete_names(self):
        mem = IFACES[self.iface]["members"]
        if self.pmap:
            return dict(self.pmap)
        if self.same_names():
            return {m_: m_ for m_ in mem}
        return {f"{self.name}_{m_}": m_ for m_ in mem}


def parse_ann(line):
    m = ANN.match(line)
    if not m or m.group(3) not in IFACES:
        return None
    rest = m.group(6)
    pmap = {}
    mm = re.search(r"\{([^}]*)\}", rest)
    if mm:
        for kv in mm.group(1).split():
            k, v = kv.split("=")
            pmap[k] = v
        rest = rest[:mm.start()]
    params = {kv.group(1): kv.group(2).strip() for kv in re.finditer(r"(\w+)\s*=\s*([^,]+)", rest)}
    return Group(m.group(2), m.group(3), m.group(4), params, pmap)


def header_span(text):
    """(module, port list '(' index, ')' index, header ';' index, {param: default}) per module."""
    mk = mask(text)
    for mm in re.finditer(r"\bmodule\s+(\w+)\s*", mk):
        i = mm.end()
        params = {}
        if mk[i] == "#":
            p0 = mk.index("(", i)
            p1 = match_paren(mk, p0)
            for x, y in split_items(mk, p0 + 1, p1):
                pm = re.search(r"(?:parameter\s+)?(?:\w+\s+)?(?:\[[^\]]*\]\s*)?(\w+)\s*=\s*(.+)$",
                               mk[x:y].strip(), re.S)
                if pm:
                    eq = x + mk[x:y].index("=")                # the '=' of the code, not one in a comment
                    v = re.sub(r"/\*.*?\*/", " ", text[eq + 1:y], flags=re.S)
                    params[pm.group(1)] = re.sub(r"//[^\n]*", " ", v).strip()
            i = p1 + 1
        j = i
        while mk[j].isspace():
            j += 1
        if mk[j] == ";":                                   # no port list (testbench top)
            yield mm.group(1), j, j, j, params
            continue
        p0 = mk.index("(", j)
        p1 = match_paren(mk, p0)
        yield mm.group(1), p0, p1, mk.index(";", p1), params


def module_groups(text):
    out = {}
    for name, p0, p1, semi, params in header_span(text):
        groups, cur = [], None
        for line in text[p0:p1].split("\n"):
            g = parse_ann(line)
            if g:
                cur = g
                groups.append(g)
                continue
            im = IFPORT.match(line)
            if im and cur and im.group(3) == cur.name and im.group(1) == cur.iface and not cur.ports:
                for p, m_ in cur.discrete_names().items():
                    d = IFACES[cur.iface]["members"][m_][0]
                    out_dir = (d == "o") == drives_o(cur.iface, cur.mp) and cur.mp not in MONITOR
                    cur.ports[p] = ("output" if out_dir else "input", "")
                cur = None
                continue
            pm = PORT.match(line)
            if pm:                                       # a group's ports need not be contiguous
                for g in reversed(groups):
                    if g.member_of(pm.group(3)) and pm.group(3) not in g.ports:
                        g.ports[pm.group(3)] = (pm.group(1), pm.group(2).strip())
                        break
        out[name] = ([g for g in groups if g.ports], params)
    return out


def walk(base):
    for dp, dn, fn in os.walk(ROOT + base):
        dn[:] = [x for x in dn if x not in SKIP]
        for f in fn:
            yield os.path.join(dp, f)


def build_table():
    for base in ("ip", "image_processing"):
        for p in walk(base):
            if p.endswith("_if.sv") and not os.path.basename(p).startswith("._"):
                load_iface_file(p)
    table = {}
    for base in ("ip", "image_processing"):
        for p in walk(base):
            if not p.endswith((".sv", ".svh")) or os.path.basename(p).startswith("._"):
                continue
            try:
                t = open(p, encoding="utf-8").read()
            except UnicodeDecodeError:
                continue
            if "module" not in t:
                continue
            try:
                for k, v in module_groups(t).items():
                    if v[0]:
                        table[k] = v
            except (ValueError, IndexError):
                pass
    return table


# ------------------------------------------------------------------ conversion
class Edit:
    def __init__(self):
        self.ed = []

    def add(self, a, b, s):
        self.ed.append((a, b, s))

    def covered(self, i):
        return any(a <= i < b for a, b, _ in self.ed if b > a)

    def apply(self, text):
        for a, b, s in sorted(self.ed, key=lambda e: (e[0], e[1]), reverse=True):
            text = text[:a] + s + text[b:]
        return text


def decls_of(text, mk, names, lo, hi):
    """Local declarations of names between lo and hi: {name: (stmt start, end, range, init, n names)}."""
    out = {}
    for dm in re.finditer(r"(?m)^[ \t]*(logic|wire|reg|bit|var\s+logic)\s+(signed\s+)?((?:\[[^\]]*\]\s*)*)([^;()]*);[ \t]*(//[^\n]*)?\n?",
                          mk[:hi]):
        if dm.start() < lo:
            continue
        items = split_items(mk, dm.start(4), dm.end(4))
        for x, y in items:
            nm = re.match(r"\s*(\w+)\s*(?:=\s*(.+))?$", text[x:y], re.S)
            if nm and nm.group(1) in names:
                out[nm.group(1)] = (dm.start(), dm.end(), dm.group(3).strip(), nm.group(2), len(items))
    return out


def mask_keep(txt):
    """Connection text for renaming: comments stay (the pattern skips '.name' and names in them only
    when they are not identifiers of the design)."""
    return txt


DECL_KW = r"(?:input|output|inout|int|integer|logic|bit|byte|shortint|longint|reg|wire|real|string)"


def shadowed(name, body_mk, path, body_text):
    """True when name is declared more than once in the module (or its `included fragments): a task or
    function argument / local variable would be renamed by mistake."""
    pat = re.compile(rf"\b{DECL_KW}\b[^;()]*?\b{re.escape(name)}\b\s*(?:[,;)=\[]|$)", re.M)
    n = len(pat.findall(body_mk))
    for inc in re.findall(r'(?m)^\s*`include\s+"([^"]+)"', body_text):
        for d in (os.path.dirname(path), os.path.join(os.path.dirname(path), "tests"),
                  os.path.join(os.path.dirname(path), "..", "tests")):
            q = os.path.normpath(os.path.join(d, inc))
            if os.path.isfile(q):
                n += len(pat.findall(mask(open(q, encoding="utf-8").read())))
                break
    return n > 1


def rename_pattern(renames):
    return re.compile(r"(?<![\w.$'])(" + "|".join(sorted(map(re.escape, renames), key=len, reverse=True))
                      + r")\b(?!\s*\()")


def block_start(mk, body0, pos):
    """Start of the innermost begin ... end block (generate block) around pos, or None at module level."""
    depth, i = 0, pos
    for m in reversed(list(re.finditer(r"\b(begin|end)\b", mk[body0:pos]))):
        if m.group(1) == "end":
            depth += 1
        elif depth:
            depth -= 1
        else:
            return body0 + m.start()
    return None


def decl_pos(P, mk, body0, body1, bundles, own_names):
    """Where interface P is declared (-1: a module port)."""
    if P in own_names:
        return -1
    if P in bundles:
        return bundles[P][2]
    m = re.search(rf"\b\w+_if\s*(#\s*\([^;]*?\))?\s*{re.escape(P)}\s*\(", mk[body0:body1])
    return body0 + m.start() if m else -1


def rename_in_file(q, renames, dry):
    t = open(q, encoding="utf-8").read()
    ed = Edit()
    for rm in rename_pattern(renames).finditer(mask(t)):
        ed.add(rm.start(), rm.end(), renames[rm.group(1)])
    if ed.ed and not dry:
        open(q, "w", encoding="utf-8").write(ed.apply(t))
    return bool(ed.ed)


def convert_module(path, text, mod, table, dry, log):
    mname, p0, p1, semi, mparams = mod
    mk = mask(text)
    body0, body1 = semi + 1, mk.index("endmodule", semi)
    body_text = text[body0:body1]
    own = table.get(mname, ([], {}))[0]
    own_names = {g.name: g for g in own}
    ed = Edit()
    bundles, renames, removed, absorbed, passed = {}, {}, {}, {}, set()
    pending, bundle_ties = [], {}                     # text inserted after the renames are known
    rebuilt, users = [], {}                           # rebuilt connection lists; instances per interface
    own_ports = {p: (g.name, g.member_of(p)) for g in own for p in g.ports}
    for im in re.finditer(r"(?m)^([ \t]*)(\w+)[ \t]*(#\s*\()?", mk[body0:body1]):
        cname = im.group(2)
        if cname not in table:
            continue
        a = body0 + im.start(2)
        i = body0 + im.end()
        over = {}
        if im.group(3):
            q0 = i - 1
            q1 = match_paren(mk, q0)
            for x, y in split_items(mk, q0 + 1, q1):
                om = re.match(r"\s*\.(\w+)\s*\((.*)\)\s*$", mk[x:y], re.S)
                if om:
                    over[om.group(1)] = text[x + om.start(2):x + om.end(2)].strip()
            i = q1 + 1
        nm = re.match(r"\s*(\w+)(\s*\[[^\]]*\])?\s*\(", mk[i:])
        if not nm:
            continue
        iname = nm.group(1)
        c0 = i + nm.end() - 1
        c1 = match_paren(mk, c0)
        groups, cparams = table[cname]
        conns = []
        for x, y in split_items(mk, c0 + 1, c1):
            seg = mk[x:y]
            if seg.strip() == ".*":
                conns.append(("*", None, (x, y)))
                continue
            cm = re.match(r"\s*\.(\w+)\s*(\((.*)\))?\s*$", seg, re.S)
            if not cm:
                conns.append((None, text[x:y], (x, y)))
                continue
            expr = text[x + cm.start(3):x + cm.end(3)].strip() if cm.group(2) else cm.group(1)
            conns.append((cm.group(1), expr, (x, y)))
        star = any(c[0] == "*" for c in conns)
        newconn, gone, pre = {}, set(), []
        for g in groups:
            cmap = {c[0]: c[1] for c in conns if c[0] in g.ports}
            if not cmap and not star:
                continue
            if any(c[0] == g.name for c in conns):           # already an interface connection
                continue
            if star:
                for p in g.ports:
                    cmap.setdefault(p, p)
            mem = {g.member_of(p): e for p, e in cmap.items()}
            ipar = {}
            for k, v in g.params.items():
                e = v
                for _ in range(4):                       # child localparams may use other parameters
                    hit = [cp for cp in sorted(cparams, key=len, reverse=True) if re.search(rf"\b{cp}\b", e)]
                    if not hit:
                        break
                    for cp in hit:
                        val = over.get(cp, cparams[cp])
                        e = re.sub(rf"\b{cp}\b", val if re.match(r"^[\w.]+$", val) else f"({val})", e)
                ipar[k] = e
            consts = {m_: e for m_, e in mem.items() if e and CONST.match(e)}
            live = {m_: e for m_, e in mem.items() if e and m_ not in consts}
            P = None
            cands = set()
            for m_, e in live.items():
                if e in own_ports and own_ports[e][1] == m_:
                    cands.add(own_ports[e][0])
                    continue
                pm = re.match(r"^(\w+)\.(\w+)$", e)
                if pm and pm.group(2) == m_:
                    cands.add(pm.group(1))
                elif e in absorbed and absorbed[e][1] == m_:
                    cands.add(absorbed[e][0])
                elif not g.pmap and not g.same_names() and e.endswith("_" + m_):
                    cands.add(e[:-len(m_) - 1])
                elif g.same_names() and e == m_:
                    cands.add(None if not star else g.name)
                else:
                    cands.add(None)
            if len(cands) == 1 and None not in cands:
                c = next(iter(cands))
                if c in own_names and any(m_ in {own_names[c].member_of(p) for p in own_names[c].ports}
                                          for m_ in consts):
                    c = None                             # a constant on a member the parent drives: adapter
                if c and (c in own_names or c in bundles or
                        re.search(rf"\b\w+_if\s*(#\s*\([^;]*?\))?\s*{c}\s*\(", mk[body0:body1])):
                    P = c
                    for m_, e in consts.items():         # the parent's interface lacks these members
                        if c not in own_names:
                            pending.append((None, f"assign {c}.{m_} = {e};"))
            if P is None and live and all(re.match(r"^\w+$", e) for e in live.values()) \
                    and len(set(live.values())) == len(live) and not any(e in absorbed for e in live.values()):
                dl = decls_of(text, mk, set(live.values()), body0, body1)
                if any(shadowed(n, mk[body0:body1], path, body_text) for n in live.values()):
                    dl = {}
                if len(dl) == len(live):
                    pref = os.path.commonprefix(list(live.values()))
                    if len(cands) == 1 and None not in cands:
                        P = next(iter(cands))
                    elif g.same_names():
                        P = g.name
                    elif pref.endswith("_") and len(pref) > 1:
                        P = pref[:-1]
                    else:
                        P = g.name
                    if P in SV_KEYWORDS:
                        P = P + "_bus"
                    if P in bundles or P in own_names or \
                            (re.search(rf"(?<![\w.]){P}\b", mk[body0:body1]) and P not in cands):
                        P = f"{iname}_{g.name}"
                    par = dict(ipar)
                    for W, member in IFACES[g.iface].get("width", {}).items():
                        net = live.get(member)
                        if net:
                            par[W] = width_of(dl[net][2])
                    bundles[P] = (g.iface, par, min(v[0] for v in dl.values()))
                    for m_, n in live.items():
                        renames[n] = f"{P}.{m_}"
                        removed[n] = dl[n]
                        absorbed[n] = (P, m_)
                    for m_, e in consts.items():
                        bundle_ties.setdefault(P, []).append(f"assign {P}.{m_} = {e};")
            if P is not None and block_start(mk, body0, a) is not None \
                    and decl_pos(P, mk, body0, body1, bundles, own_names) < block_start(mk, body0, a):
                # Icarus 14: an interface declared outside a generate block cannot be handed to an
                # instance inside it - a block-local interface bridged member by member instead
                A = f"{iname}_{g.name}"
                ind = im.group(1)
                pstr = ", ".join(f".{k}({v})" for k, v in ipar.items())
                pre.append(f"{ind}{g.iface}{' #(' + pstr + ')' if pstr else ''} {A} ();   // bridge (generate scope)\n")
                for m_, (d, _) in IFACES[g.iface]["members"].items():
                    child_out = (d == "o") == drives_o(g.iface, g.mp) and g.mp not in MONITOR
                    pre.append(f"{ind}assign {P}.{m_} = {A}.{m_};\n" if child_out else f"{ind}assign {A}.{m_} = {P}.{m_};\n")
                newconn[g.name] = A
                log.append(f"  bridge {A} in {mname} (generate block, {P} declared outside)")
            elif P is not None:
                newconn[g.name] = P
            else:
                A = f"{iname}_{g.name}"
                ind = im.group(1)
                pstr = ", ".join(f".{k}({v})" for k, v in ipar.items())
                pre.append(f"{ind}{g.iface}{' #(' + pstr + ')' if pstr else ''} {A} ();\n")
                for p, e in list(cmap.items()):
                    if not e:
                        continue
                    m_ = g.member_of(p)
                    pre.append(f"{ind}assign {e} = {A}.{m_};\n" if g.ports[p][0] == "output"
                               else f"{ind}assign {A}.{m_} = {e};\n")
                newconn[g.name] = A
                log.append(f"  adapter {A} in {mname}")
            gone.update(g.ports)
        if not newconn:
            continue
        passed.update(newconn.values())
        ind, lines, done_g = None, [], set()
        for port, expr, (x, y) in conns:
            seg = text[x:y]
            lead = re.match(r"\s*", seg).group(0)
            if ind is None and "\n" in lead:
                ind = lead.split("\n")[-1]
            if port in gone:
                g = next(g for g in groups if port in g.ports)
                if g.name not in done_g and g.name in newconn:
                    done_g.add(g.name)
                    lines.append(f".{g.name}({newconn[g.name]})")
                continue
            if port == "*":
                for g in groups:
                    if g.name in newconn and g.name not in done_g and newconn[g.name] != g.name:
                        done_g.add(g.name)
                        lines.append(f".{g.name}({newconn[g.name]})")
            lines.append(seg.strip())
        ind = ind or "    "
        close_ind = re.match(r"[ \t]*", text[text.rfind("\n", 0, c1) + 1:]).group(0)
        rebuilt.append((c0 + 1, c1, "\n" + ",\n".join(ind + l for l in lines) + "\n" + close_ind))
        for v in newconn.values():
            users[v] = users.get(v, 0) + 1
        if pre:
            pending.append((text.rfind("\n", 0, a) + 1, "".join(pre)))
        log.append(f"  {cname} {iname}: " + ", ".join(f"{k}->{v}" for k, v in newconn.items()))
    # bundle declarations
    stmts = {}
    for n, info in removed.items():
        stmts.setdefault((info[0], info[1]), []).append(n)
    for (s0, s1), names in stmts.items():
        info0 = removed[names[0]]
        if len(names) == info0[4]:
            ed.add(s0, s1, "")
        else:
            stmt = text[s0:s1]
            dm = re.match(r"([ \t]*(?:logic|wire|reg|bit|var\s+logic)\s+(?:signed\s+)?(?:\[[^\]]*\]\s*)*)([^;]*);(.*)$",
                          stmt, re.S)
            keep = []
            for x, y in split_items(dm.group(2), 0, len(dm.group(2))):
                if re.match(r"\s*(\w+)", dm.group(2)[x:y]).group(1) not in names:
                    keep.append(dm.group(2)[x:y].strip())
            ed.add(s0, s1, dm.group(1) + ", ".join(keep) + ";" + dm.group(3))
    for P, (iface, par, pos) in bundles.items():
        ls = text.rfind("\n", 0, pos) + 1
        ind = re.match(r"[ \t]*", text[ls:]).group(0)
        pstr = ", ".join(f".{k}({v})" for k, v in par.items())
        inits = []
        for n, info in removed.items():
            if renames[n].startswith(P + ".") and info[3]:
                kw = "assign" if re.match(r"[ \t]*wire", text[info[0]:info[1]]) else "initial"
                inits.append(f"{ind}{kw} {renames[n]} = {info[3].strip()};\n")
        # constant ties only when no other instance drives the bundle (its module ties what it lacks)
        ties = "".join(f"{ind}{t}\n" for t in bundle_ties.get(P, [])) if users.get(P, 0) <= 1 else ""
        ed.add(ls, ls, f"{ind}{iface}{' #(' + pstr + ')' if pstr else ''} {P} ();\n" + "".join(inits) + ties)
        log.append(f"  bundle {P}: {iface} {pstr}")
    # own port groups
    hdr = text[p0:p1].split("\n")
    offs, pos = [], p0
    for ln in hdr:
        offs.append(pos)
        pos += len(ln) + 1
    pl = [i for i, ln in enumerate(hdr) if PORT.match(ln) or IFPORT.match(ln)]
    last_port = max(pl) if pl else -1
    tie = []
    for g in own:
        idx = [i for i, ln in enumerate(hdr) if PORT.match(ln) and PORT.match(ln).group(3) in g.ports]
        if not idx:
            continue
        ind = re.match(r"[ \t]*", hdr[idx[0]]).group(0)
        last = idx[-1] == last_port
        for k, i in enumerate(idx):
            ed.add(offs[i], offs[i] + len(hdr[i]) + 1,
                   f"{ind}{g.iface}.{g.mp} {g.name}{'' if last else ','}\n" if k == 0 else "")
        for p in g.ports:
            renames[p] = f"{g.name}.{g.member_of(p)}"
        have = {g.member_of(p) for p in g.ports}
        if g.name not in passed and g.mp not in MONITOR:
            want = "o" if drives_o(g.iface, g.mp) else "i"
            # a port inside `ifdef / `ifndef: its tie-offs under the same condition
            conds = []
            for ln in hdr[:idx[0]]:
                cm = re.match(r"\s*`(ifdef|ifndef|else|endif|elsif)\b\s*(\w*)", ln)
                if cm:
                    if cm.group(1) in ("ifdef", "ifndef"):
                        conds.append([cm.group(1), cm.group(2)])
                    elif cm.group(1) == "endif" and conds:
                        conds.pop()
                    elif cm.group(1) == "else" and conds:
                        conds[-1][0] = "ifndef" if conds[-1][0] == "ifdef" else "ifdef"
            ties = [f"  assign {g.name}.{m_} = {tv};      // not used by this block\n"
                    for m_, (d, tv) in IFACES[g.iface]["members"].items()
                    if d == want and m_ not in have and tv is not None]
            if ties and conds:
                ties = [f"`{c} {n}\n" for c, n in conds] + ties + ["`endif\n"] * len(conds)
            tie += ties
        log.append(f"  port {g.name}: {g.iface}.{g.mp}")
    if tie:
        ed.add(semi + 1, semi + 1, "\n" + "".join(tie).rstrip("\n"))
    def in_rebuilt(i):
        return any(a0 <= i < a1 for a0, a1, _ in rebuilt)
    if renames:
        pat = rename_pattern(renames)
        for rm in pat.finditer(mk, body0, body1):
            if not ed.covered(rm.start()) and not in_rebuilt(rm.start()):
                ed.add(rm.start(), rm.end(), renames[rm.group(1)])
        # connection shorthand '.name' of a renamed net -> '.name(new)'
        for sm in re.finditer(r"\.(\w+)(?=\s*[,)])", mk[body0:body1]):
            a0 = body0 + sm.start()
            if sm.group(1) in renames and not ed.covered(a0) and not in_rebuilt(a0):
                ed.add(a0, body0 + sm.end(), f".{sm.group(1)}({renames[sm.group(1)]})")
    for a0, a1, txt in rebuilt:
        if renames:
            txt = rename_pattern(renames).sub(lambda mm_: renames[mm_.group(1)], mask_keep(txt))
            txt = re.sub(r"\.(\w+)(?=\s*(,|\n|$))",
                         lambda mm_: f".{mm_.group(1)}({renames[mm_.group(1)]})" if mm_.group(1) in renames
                         else mm_.group(0), txt)
        ed.add(a0, a1, txt)
    for pos, txt in pending:
        if renames:
            txt = rename_pattern(renames).sub(lambda mm_: renames[mm_.group(1)], txt)
        if pos is None:
            pos = semi + 1
            txt = "\n  " + txt
        ed.add(pos, pos, txt)
    text = ed.apply(text)
    if renames:
        for inc in re.findall(r'(?m)^\s*`include\s+"([^"]+)"', body_text):
            for d in (os.path.dirname(path), os.path.join(os.path.dirname(path), "tests"),
                      os.path.join(os.path.dirname(path), "..", "tests")):
                q = os.path.normpath(os.path.join(d, inc))
                if os.path.isfile(q):
                    if rename_in_file(q, renames, dry):
                        log.append(f"  renamed in {os.path.relpath(q, ROOT)}")
                    break
    return text


def reorder_passthrough(text):
    """Icarus 14 cannot reference members of an interface port after the port has been handed to a
    child instance (earlier references work). A module-level instance that receives one of the
    module's interface ports, followed by references to that port, is moved to the end of the
    module (instance order has no meaning in SystemVerilog). Returns (text, moved instance names)."""
    moved = []
    for name, p0, p1, semi, _ in reversed(list(header_span(text))):
        mk = mask(text)
        end = mk.find("endmodule", semi)
        if end < 0:
            continue
        ports = {m.group(3) for m in (IFPORT.match(l) for l in text[p0:p1].split("\n")) if m}
        if not ports:
            continue
        body = mk[semi + 1:end]
        for im in reversed(list(re.finditer(r"(?m)^([ \t]*)(\w+)[ \t]*(#\s*\()?", body))):
            a = semi + 1 + im.start()
            i = semi + 1 + im.end()
            if im.group(2) in SV_KEYWORDS:
                continue
            if im.group(3):
                i = match_paren(mk, i - 1) + 1
            nm = re.match(r"\s*(\w+)\s*\(", mk[i:end])
            if not nm or nm.group(1) in SV_KEYWORDS:
                continue
            c0 = i + nm.end() - 1
            try:
                c1 = match_paren(mk, c0)
            except ValueError:
                continue
            se = mk.find(";", c1)
            if se < 0 or mk[c1 + 1:se].strip():
                continue
            pre = mk[semi + 1:a]
            if len(re.findall(r"\bbegin\b", pre)) != len(re.findall(r"\bend\b", pre)):
                continue                                     # inside a generate block
            passed = {pm.group(1) for pm in re.finditer(r"\.\w+\s*\(\s*(\w+)\s*\)", mk[c0:c1]) if pm.group(1) in ports}
            after = mk[se + 1:end]
            if not passed or not any(re.search(rf"\b{p}\s*\.\s*\w", after) for p in passed):
                continue
            # the statement with its comment lines just above
            st = a
            while True:
                prev = text.rfind("\n", 0, st - 1) + 1
                if st > 0 and text[prev:st].strip().startswith("//"):
                    st = prev
                else:
                    break
            stmt_end = text.find("\n", se) + 1
            block = text[st:stmt_end]
            mk_end = mask(text).find("endmodule", stmt_end)
            text = text[:st] + text[stmt_end:mk_end] + block + text[mk_end:]
            moved.append(f"{name}.{nm.group(1)}")
            mk = mask(text)
            end = mk.find("endmodule", semi)
    return text, moved


def convert_file(path, table, dry=False):
    text = open(path, encoding="utf-8").read()
    orig, log = text, []
    for mod in reversed(list(header_span(text))):     # last to first: earlier positions stay valid
        if "endmodule" not in mask(text)[mod[3]:]:
            continue                                   # not a complete module (fragment)
        text = convert_module(path, text, mod, table, dry, log)
    text, moved = reorder_passthrough(text)
    log += [f"  moved to the end (Icarus: port used after hand-over): {m}" for m in moved]
    if text != orig and not dry:
        open(path, "w", encoding="utf-8").write(text)
    return log


def main():
    args = sys.argv[1:]
    dry = "--dry" in args
    args = [a for a in args if a != "--dry"]
    if not args:
        sys.exit(__doc__ or "usage: sv_ifconv.py [--dry] FILE...")
    table = build_table()
    for f in args:
        p = f if f.startswith("/") else os.path.abspath(f)
        lg = convert_file(p, table, dry)
        print(os.path.relpath(p, ROOT) + (":" if lg else ": unchanged"))
        for line in lg:
            print(line)


if __name__ == "__main__":
    main()

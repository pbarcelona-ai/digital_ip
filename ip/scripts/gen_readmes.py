#!/usr/bin/env python3
# ***************
# Filename: gen_readmes.py
# Author: FPGA Cores 4 U
# Description: Gives every IP (ip/<category>/<ip>, the design-local IP of the
#   systems, the examples) and every design that contains several IPs
#   (image_processing/<system>) its own README.md, and keeps a generated part
#   of it current. A missing README.md is created with the title, the
#   description from the top module's header and the directory layout. Every
#   README.md then gets (or has refreshed) the block between
#     <!-- readme:begin ... -->  and  <!-- readme:end -->
#   holding: the `make help` text (or how the block is built and tested when it
#   has no Makefile of its own), the tests (ip/scripts/list_tests.py), the
#   register information (docs/<ip>_regs.md and the register-map files in
#   src/include/, else where the map is described, or no register interface)
#   and the generation prompt (docs/<name>_prompt.md). Text outside the block
#   is never changed. The diagrams are added by update_readme_diagrams.py,
#   which this script runs at the end (--no-diagrams skips it).
# Date: 2026-10-11
# ***************
"""Usage: python3 ip/scripts/gen_readmes.py [--dry-run] [--only NAME ...] [--no-diagrams]"""
from __future__ import annotations

import argparse
import csv
import os
import re
import subprocess
import sys
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent
IP_ROOT = SCRIPTS.parent                                  # digital_ip/ip
REPO = IP_ROOT.parent                                     # digital_ip
SYSTEMS_ROOT = REPO / "image_processing"
BEGIN = "<!-- readme:begin (generated by ip/scripts/gen_readmes.py; edits here are overwritten) -->"
END = "<!-- readme:end -->"
BLOCK_RE = re.compile(r"\n*<!-- readme:begin.*?<!-- readme:end -->\n*", re.S)
# bus fabric: AXI4-Lite ports but no registers of their own
FABRIC = {"axi4_lite_cdc", "axi4_lite_slave", "axi4_lite_decoder", "axi4_lite_mux", "py_axil_xbar", "axil_regbus",
          "axil_split", "ip_axil_regs", "axi_checkers"}


class Block:
    def __init__(self, name: str, path: Path, top: str, kind: str, parent: Path | None = None):
        self.name, self.path, self.top, self.kind, self.parent = name, path, top, kind, parent


def blocks() -> list[Block]:
    out = []
    for row in csv.reader(l for l in (SCRIPTS / "ips.csv").read_text().splitlines() if l and not l.startswith("#")):
        if len(row) >= 3:
            name, cat, top = (c.strip() for c in row[:3])
            d = IP_ROOT / cat / name
            if d.is_dir():
                out.append(Block(name, d, top, "ip"))
    for sysdir in sorted(p for p in SYSTEMS_ROOT.iterdir() if (p / "src").is_dir()):
        out.append(Block(sysdir.name, sysdir, sysdir.name, "design"))
        for sub in sorted(p for p in (sysdir / "ip").iterdir() if (p / "src").is_dir()) if (sysdir / "ip").is_dir() else []:
            out.append(Block(sub.name, sub, sub.name, "local", parent=sysdir))
    for ex in sorted(p for p in (IP_ROOT / "examples").iterdir() if p.is_dir()):
        top = next((s.stem for s in sorted(ex.glob("*.sv"))), ex.name)
        out.append(Block(ex.name, ex, top, "example"))
    return out


def rel(target: Path, readme: Path) -> str:
    return os.path.relpath(target, readme.parent).replace(os.sep, "/")


def top_source(b: Block) -> Path | None:
    for c in (b.path / "src" / f"{b.top}.sv", b.path / "src" / f"{b.name}.sv", b.path / f"{b.top}.sv"):
        if c.is_file():
            return c
    srcs = sorted((b.path / "src").glob("*.sv")) if (b.path / "src").is_dir() else []
    return srcs[0] if srcs else None


def description(src: Path | None) -> str:
    """The Description of a file header (// ***** block), as one paragraph."""
    if not src:
        return ""
    lines = src.read_text(encoding="utf-8", errors="replace").splitlines()
    i = next((k for k, l in enumerate(lines) if "Description:" in l), None)
    if i is None:
        return ""
    words = [lines[i].split("Description:", 1)[1].strip()]
    for l in lines[i + 1:]:
        if not l.startswith("//") or "Date:" in l or l.startswith("// ****"):
            break
        words.append(l[2:].strip())
    return " ".join(w for w in words if w)


def make_help(b: Block) -> str | None:
    if not (b.path / "Makefile").is_file():
        return None
    r = subprocess.run(["make", "-s", "--no-print-directory", "help"], cwd=b.path, capture_output=True, text=True,
                       timeout=60)
    return r.stdout.rstrip() if r.returncode == 0 and r.stdout.strip() else None


def tests_md(b: Block) -> str:
    r = subprocess.run([sys.executable, str(SCRIPTS / "list_tests.py"), str(b.path), "--markdown"],
                       capture_output=True, text=True, timeout=60)
    t = r.stdout.strip()
    return t if r.returncode == 0 and t.count("\n") >= 2 else ""


def has_axil(b: Block) -> bool:
    src = top_source(b)
    return bool(src) and "s_axil_awaddr" in src.read_text(encoding="utf-8", errors="replace")


def used_blocks(b: Block) -> list[Path]:
    """IP directories (with a src/) whose sources a design's file list uses, in file-list order."""
    out = []
    for bf in (b.path / "scripts" / "build.f", b.path / "src" / "build.f"):
        if not bf.is_file():
            continue
        for line in bf.read_text().splitlines():
            line = line.split("#", 1)[0].split("//", 1)[0].strip()
            if not line or line.startswith("+"):
                continue
            f = (bf.parent.parent / line).resolve() if bf.parent.name == "scripts" else (bf.parent / line).resolve()
            parts = f.parts
            if "src" in parts:
                d = Path(*parts[:parts.index("src")])
                if d != b.path.resolve() and d not in out:
                    out.append(d)
    return out


def registers_md(b: Block, readme: Path) -> str:
    if b.kind == "design":
        lines = [f"- address map: the CPU address map in this README; each block's own register map:"]
        for d in used_blocks(b):
            mds = sorted((d / "docs").glob("*_regs.md")) if (d / "docs").is_dir() else []
            for md in mds:
                lines.append(f"  - [`{d.name}`]({rel(md, readme)})")
            if not mds and d.name not in FABRIC:
                srcs = [p for p in sorted((d / "src").glob("*.sv")) if p.stem not in FABRIC
                        and re.search(r"input\s+logic\s*(\[[^]]*\])?\s*s_axil_awaddr", p.read_text(errors="replace"))]
                if srcs:
                    links = ", ".join(f"[`{p.name}`]({rel(p, readme)})" for p in srcs)
                    lines.append(f"  - `{d.name}`: in the header{'s' if len(srcs) > 1 else ''} of {links}")
        return "\n".join(lines)
    inc = b.path / "src" / "include"
    maps = sorted(inc.glob("*_regs.json")) if inc.is_dir() else []
    if maps:
        lines = []
        for j in maps:
            stem = j.name[:-len(".json")]
            md = b.path / "docs" / f"{stem}.md"
            files = [f"[`{p.name}`]({rel(p, readme)})" for p in (inc / f"{stem}.json", inc / f"{stem}.sv",
                                                                 inc / f"{stem}.xml", inc / f"{stem}.h") if p.is_file()]
            first = f"[register map]({rel(md, readme)})" if md.is_file() else "register map"
            lines.append(f"- {first}: ID / VERSION / DATE at 0x00-0x08, the registers from 0x10; source "
                         f"{files[0]} (edit it and run `python3 {rel(SCRIPTS / 'regmap_gen.py', readme)} "
                         f"{rel(j, readme)}`), generated {', '.join(files[1:])}")
        return "\n".join(lines)
    pkg = sorted((b.path / "src").glob("*map_pkg.sv")) + sorted((b.path / "include").glob("*map_pkg.sv")) \
        if b.kind == "design" else []
    if pkg:
        return "\n".join(f"- memory map: [`{p.name}`]({rel(p, readme)})" for p in pkg)
    if has_axil(b):
        src = top_source(b)
        return (f"- AXI4-Lite register map: described in the header of [`{src.name}`]({rel(src, readme)}) "
                "(to move to src/include/ as a generated map, see "
                f"[REGMAP_MIGRATION.md]({rel(IP_ROOT / 'docs' / 'REGMAP_MIGRATION.md', readme)}))")
    return "- No register interface."


def prompt_md(b: Block, readme: Path) -> str:
    p = b.path / "docs" / f"{b.name}_prompt.md"
    if not p.is_file():
        p = next(iter(sorted((b.path / "docs").glob("*_prompt.md"))), None) if (b.path / "docs").is_dir() else None
    if p:
        return (f"- [{p.name}]({rel(p, readme)}): the prompt that regenerates this block, reverse-engineered from its "
                f"sources (`python3 {rel(SCRIPTS / 'make_ip_prompts.py', readme)} --only {b.name}`)")
    return "- No prompt yet (`python3 ip/scripts/make_ip_prompts.py` writes one)."


def section(b: Block, readme: Path) -> str:
    parts = []
    h = make_help(b)
    parts.append("## Make targets\n")
    if h:
        parts.append(f"```\n{h}\n```\n")
    elif b.kind == "local":
        parts.append(f"No Makefile of its own: built and tested with the design, see "
                     f"[`{b.parent.name}`]({rel(b.parent / 'README.md', readme)}).\n")
    elif b.kind == "example":
        parts.append("No Makefile: an example of the generators (see the files below).\n")
    else:
        parts.append("No Makefile.\n")
    t = tests_md(b)
    if t:
        parts.append("## Tests\n")
        parts.append(t + "\n")
    parts.append("## Registers\n")
    parts.append(registers_md(b, readme) + "\n")
    parts.append("## Prompt\n")
    parts.append(prompt_md(b, readme) + "\n")
    return "\n".join(parts)


def new_readme(b: Block) -> str:
    title = b.name
    desc = description(top_source(b)) or f"The {b.name} block."
    lay = []
    src_what = "RTL" + (" (`include/`: the register map files)" if (b.path / "src" / "include").is_dir() else "")
    for sub, what in (("src", src_what), ("tb", "self-checking testbench, tests in `tb/tests/`"),
                      ("scripts", "file lists (`build.f`) and flow scripts"), ("docs", "diagrams, prompt, register table, web page")):
        if (b.path / sub).is_dir():
            lay.append(f"| `{sub}/` | {what} |")
    layout = ("\n## Directory structure\n\n| Path | Contents |\n|------|----------|\n" + "\n".join(lay) + "\n") if lay else ""
    where = {"ip": "an IP of the FPGA Cores 4 U digital IP library",
             "local": "design-local IP",
             "example": "an example of the library's generators", "design": "a design built from several IPs"}[b.kind]
    if b.kind == "local":
        where = f"design-local IP of [`{b.parent.name}`](../../README.md)"
    return f"# {title}\n\n{desc}\n\n{title} is {where}.\n{layout}"


def place(text: str, block: str) -> str:
    """Replace the generated block, or insert it before the Diagrams block / closing sections, or append it."""
    blk = f"{BEGIN}\n{block.rstrip()}\n{END}"
    if BLOCK_RE.search(text):
        return BLOCK_RE.sub(lambda _: "\n\n" + blk + "\n\n", text, count=1).rstrip() + "\n"
    m = re.search(r"^<!-- diagrams:begin|^## (Documentation|License|Design notes)\b", text, re.M)
    if m:
        return text[:m.start()].rstrip() + "\n\n" + blk + "\n\n" + text[m.start():]
    return text.rstrip() + "\n\n" + blk + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--no-diagrams", action="store_true")
    a = ap.parse_args()
    created = updated = same = 0
    for b in blocks():
        if a.only and b.name not in a.only:
            continue
        readme = b.path / "README.md"
        old = readme.read_text(encoding="utf-8") if readme.is_file() else None
        text = place(old if old is not None else new_readme(b), section(b, readme))
        if text == old:
            same += 1
            continue
        if old is None:
            created += 1
            print(f"create {readme.relative_to(REPO)}")
        else:
            updated += 1
            print(f"update {readme.relative_to(REPO)}")
        if not a.dry_run:
            readme.write_text(text, encoding="utf-8")
    print(f"{created} README.md created, {updated} updated, {same} unchanged{' (dry run)' if a.dry_run else ''}")
    if not a.dry_run and not a.no_diagrams:
        subprocess.run([sys.executable, str(SCRIPTS / "update_readme_diagrams.py")], check=True,
                       stdout=subprocess.DEVNULL)
        print("diagrams: update_readme_diagrams.py run")


if __name__ == "__main__":
    main()
